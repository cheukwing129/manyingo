'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sources = [
  'question-pack-02.js',
  'question-pack-03.js',
  'question-pack-lesson.js',
  'question-pack-capacity-01.js',
  'question-pack-transfer-01.js',
  'question-pack-transfer-03.js',
  'question-pack-transfer-04.js',
  'question-pack-transfer-05.js',
  'question-pack-transfer-06.js',
  'question-pack-transfer-07.js',
  'question-pack-settext-language-01.js',
  'question-pack-settext-language-02.js',
  'question-pack-fill-01.js',
  'question-pack-reorder-01.js'
];
const output = path.join(root, 'public', 'question-packs-core.js');

function build() {
  const banner = `/* Generated by scripts/build_question_pack_bundle.cjs from ${sources.length} reviewed packs. Do not edit directly. */\n`;
  return banner + sources.map(file => `/* ${file} */\n${fs.readFileSync(path.join(root, 'public', file), 'utf8').trim()}\n`).join(';\n');
}

const expected = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
  if (current !== expected) {
    console.error('public/question-packs-core.js is stale; run node scripts/build_question_pack_bundle.cjs');
    process.exit(1);
  }
  console.log('Question pack bundle is current.');
} else {
  fs.writeFileSync(output, expected);
  console.log(`Wrote ${path.relative(root, output)} from ${sources.length} reviewed packs.`);
}

module.exports = { sources, build };
